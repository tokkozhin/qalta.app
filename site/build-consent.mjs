// Generates public/oauth/consent/config.js from the public Supabase values.
// Run explicitly with `npm run consent:config`; the publishable key is safe in a
// browser, a secret key is rejected.
import fs from "node:fs";
import path from "node:path";

const root = process.cwd();

function readEnvFile(fileName) {
  const file = path.join(root, fileName);
  if (!fs.existsSync(file)) return {};
  const env = {};
  for (const line of fs.readFileSync(file, "utf8").split(/\r?\n/)) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith("#")) continue;
    const equals = trimmed.indexOf("=");
    if (equals < 0) continue;
    const key = trimmed.slice(0, equals).trim();
    let value = trimmed.slice(equals + 1).trim();
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }
    env[key] = value;
  }
  return env;
}

const fileEnv = { ...readEnvFile(".env"), ...readEnvFile(".env.local") };
const pick = (key) => process.env[key] || fileEnv[key];

const supabaseUrl =
  pick("SUPABASE_URL") || pick("EXPO_PUBLIC_SUPABASE_URL");
const publishableKey =
  pick("SUPABASE_PUBLISHABLE_KEY") || pick("EXPO_PUBLIC_SUPABASE_PUBLISHABLE_KEY");
const siteUrl = pick("CONSENT_SITE_URL") || "https://qalta.app";

if (!supabaseUrl || !publishableKey) {
  console.error(
    "Missing SUPABASE_URL or SUPABASE_PUBLISHABLE_KEY. Set them in the " +
      "Cloudflare Pages environment (or .env/.env.local), then build again.",
  );
  process.exit(1);
}
let isPublicKey = publishableKey.startsWith("sb_publishable_");
if (!isPublicKey) {
  try {
    const claims = JSON.parse(Buffer.from(publishableKey.split(".")[1], "base64url").toString());
    isPublicKey = claims.role === "anon";
  } catch { /* Invalid keys and legacy service-role JWTs must never be published. */ }
}
if (!isPublicKey) {
  console.error("Refusing to write a secret key into a public page.");
  process.exit(1);
}

const output = `// Generated by site/build-consent.mjs from public project values.
window.QALTA_AUTH_CONFIG = ${JSON.stringify(
  { supabaseUrl, supabasePublishableKey: publishableKey, siteUrl },
  null,
  2,
)};
`;

const target = path.join(root, "public/oauth/consent/config.js");
fs.mkdirSync(path.dirname(target), { recursive: true });
fs.writeFileSync(target, output);
console.log(`Wrote ${path.relative(root, target)}`);
